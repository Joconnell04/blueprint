class Helpers(unittest.TestCase):

    def test_number_format_families(self):
        self.assertEqual(ef.nf_family("$#,##0;($#,##0)"), "currency")
        self.assertEqual(ef.nf_family("$#,##0.00;($#,##0.00)"), "currency2")
        self.assertEqual(ef.nf_family("0.0%"), "percent")
        self.assertEqual(ef.nf_family('0.0"x"'), "multiple")
        self.assertEqual(ef.nf_family("#,##0"), "count")
        self.assertIsNone(ef.nf_family("General"))
        self.assertIsNone(ef.nf_family("@"))

    def test_one_reading_never_reaches_high_confidence(self):
        self.assertLess(ef.score(1.0, 1), 0.8)
        self.assertGreaterEqual(ef.score(1.0, 3), 0.8)
        self.assertEqual(ef.score(1.0, 0), 0.0)
        self.assertLess(ef.score(0.5, 20), 0.6)

    def test_grey_excludes_black_and_white(self):
        self.assertTrue(ef.is_grey("595959"))
        self.assertTrue(ef.is_grey("666666"))
        self.assertFalse(ef.is_grey("000000"))
        self.assertFalse(ef.is_grey("FFFFFF"))
        self.assertFalse(ef.is_grey("0000FF"))

    def test_points_map_to_grid_cells(self):
        self.assertEqual(ef.cell_of(0, 0), [1, 1])
        self.assertEqual(ef.cell_of(32, 108), [2, 5])
        self.assertEqual(ef.cell_of(888, 25), [31, 2])

    def test_font_family_strips_weight_and_slope_words(self):
        self.assertEqual(ef.font_family("Montserrat SemiBold"), "Montserrat")
        self.assertEqual(ef.font_family("Montserrat Light Italic"), "Montserrat")
        self.assertEqual(ef.font_family("Lato Black"), "Lato")
        self.assertEqual(ef.font_family("Helvetica Neue"), "Helvetica Neue")
        self.assertEqual(ef.font_family("Times New Roman"), "Times New Roman")
        self.assertEqual(ef.font_family("Montserrat"), "Montserrat")

    def test_a_face_keeps_its_weight_only_when_the_file_declares_it(self):
        book = ef.FaceBook()
        book.add("Montserrat SemiBold", 200)
        self.assertEqual(book.best(("Montserrat SemiBold",))[0], "Montserrat SemiBold")
        self.assertEqual(book.best(("Montserrat",))[0], "Montserrat", "an undeclared face is its family")
        book.add("Montserrat Light", 250)       # no face carries the family on its own now
        self.assertEqual(book.best(("Montserrat SemiBold", "Montserrat Light"))[0], "Montserrat")

    def test_faces_of_one_family_are_counted_together(self):
        book = ef.FaceBook()
        book.add("Montserrat", 100)
        book.add("Montserrat Light", 90)
        book.add("Lato", 120)
        name, share, runs, found = book.best(())
        self.assertEqual(name, "Montserrat")    # 190 characters of Montserrat beat 120 of Lato
        self.assertEqual(runs, 2)
        self.assertEqual(sorted(found), ["Montserrat", "Montserrat Light"])
        self.assertAlmostEqual(share, 190 / 310.0, places=3)

    def test_text_case(self):
        self.assertEqual(ef.text_case("Strategic Rationale | Why Referrals"), "title")
        self.assertEqual(ef.text_case("Referrals already carry a third of new partners"), "sentence")
        self.assertEqual(ef.text_case("TODAY"), "upper")

    def test_yaml_values_round_trip_through_the_builder_parser(self):
        for value in ("$#,##0;($#,##0)", '0.0"x"', "0000FF", "Arial", "0.0%", 10, True, False):
            line = "  key: %s" % ef.yaml_value(value)
            md = "---\nformat:\n%s\n---\n" % line
            back = build_xlsx.front_matter(md)["format"]["key"]
            self.assertEqual(back, "true" if value is True else
                             ("false" if value is False else str(value)))



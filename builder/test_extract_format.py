def front_matter_text(md):
    match = re.match(r"\A---[ \t]*\r?\n(.*?)\r?\n---[ \t]*\r?\n", md, re.S)
    assert match, "no front matter"
    return match.group(1)


def check_yaml_subset(case, text):
    """Front matter is a flat map of scalars and two-space blocks; check that shape."""
    for line in text.splitlines():
        if not line.strip():
            continue
        case.assertNotIn("\t", line, "tabs are not YAML indentation")
        indent = len(line) - len(line.lstrip(" "))
        case.assertIn(indent, (0, 2), line)
        case.assertRegex(line.strip(), r"^[A-Za-z0-9_.\-]+:( .*)?$", line)
        value = line.split(":", 1)[1].strip()
        if value and value[0] not in "\"'":
            case.assertNotIn("#", value, "an unquoted # starts a YAML comment: %s" % line)
            case.assertNotIn(": ", value, "an unquoted colon breaks the map: %s" % line)



MONTSERRAT = "Montserrat"
MONTSERRAT_SEMI = "Montserrat SemiBold"
MONTSERRAT_LIGHT = "Montserrat Light"
HEADLINE = "Retention is compounding and the next raise is funded by it"
BODY_ONE = ("Retention in the 2024 cohort runs eleven points above the 2023 cohort at "
            "month twelve, and the gap widens every month after that.")
BODY_TWO = "Nothing in pricing moved, so the gap is retention and not the price card."


def _theme_fonts(prs, major, minor):
    """Rewrite the theme's font scheme; python-pptx has no API for it."""
    from pptx.opc.constants import RELATIONSHIP_TYPE as RT
    part = prs.slide_masters[0].part.part_related_by(RT.THEME)
    xml = part.blob.decode("utf-8")
    start = xml.index("<a:fontScheme")
    end = xml.index("</a:fontScheme>") + len("</a:fontScheme>")
    scheme = (
        '<a:fontScheme name="%s">'
        '<a:majorFont><a:latin typeface="%s"/><a:ea typeface=""/><a:cs typeface=""/></a:majorFont>'
        '<a:minorFont><a:latin typeface="%s"/><a:ea typeface=""/><a:cs typeface=""/></a:minorFont>'
        "</a:fontScheme>" % (minor, major, minor)
    )
    part._blob = (xml[:start] + scheme + xml[end:]).encode("utf-8")


def _paras(frame, paras):
    """One paragraph per (text, size, font), each a single run that names its face."""
    from pptx.util import Pt
    from pptx.dml.color import RGBColor
    for i, (text, size, font) in enumerate(paras):
        para = frame.paragraphs[0] if i == 0 else frame.add_paragraph()
        run = para.add_run()
        run.text = text
        run.font.size = Pt(size)
        run.font.color.rgb = RGBColor.from_string("1F2937")
        if font:
            run.font.name = font


def _box(slide, x, y, w, h, paras):
    from pptx.util import Pt
    box = slide.shapes.add_textbox(Pt(x), Pt(y), Pt(w), Pt(h))
    box.text_frame.word_wrap = True
    _paras(box.text_frame, paras)
    return box


def _content(prs, font_body, font_light, font_head):
    """One content slide: kicker, headline, two body paragraphs, a card, a source."""
    from pptx.util import Pt
    from pptx.enum.shapes import MSO_SHAPE
    slide = make_fixtures._blank(prs, "FFFFFF")
    _box(slide, 32, 73, 500, 20, [("Context | Where we landed", 16, font_body)])
    _box(slide, 32, 108, 868, 70, [(HEADLINE, 28, font_head)])
    _box(slide, 32, 200, 520, 90, [(BODY_ONE, 12, font_body), (BODY_TWO, 12, font_light)])
    card = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Pt(600), Pt(200), Pt(300), Pt(180))
    card.text_frame.word_wrap = True
    _paras(card.text_frame, [("Open networks", 17, font_body), ("Reach", 14, font_light),
                             ("Partners sit inside networks the team cannot buy into, and a "
                              "referred partner arrives believing the case.", 12, font_light)])
    _box(slide, 32, 500, 400, 16, [("Source: partner CRM, 2025", 10, font_light)])
    return slide


def _poppins_deck(path):
    """Theme Calibri, runs Montserrat: a title, two content slides and a divider."""
    from pptx import Presentation
    from pptx.util import Emu
    prs = Presentation()
    prs.slide_width = Emu(960 * 12700)
    prs.slide_height = Emu(540 * 12700)
    _theme_fonts(prs, "Calibri", "Calibri")
    title = make_fixtures._blank(prs, "111111")
    _box(title, 32, 300, 700, 60, [("Q3 board update", 44, MONTSERRAT_SEMI)])
    _box(title, 32, 380, 400, 20, [("Working draft", 14, MONTSERRAT)])
    _content(prs, MONTSERRAT, MONTSERRAT_LIGHT, MONTSERRAT_SEMI)
    _content(prs, MONTSERRAT, MONTSERRAT_LIGHT, MONTSERRAT_SEMI)
    # A divider is furniture: its font must not reach the tokens, so set it in the theme's.
    divider = make_fixtures._blank(prs, "111111")
    _box(divider, 32, 81, 800, 100, [("Where growth comes from", 66, "Calibri")])
    prs.save(path)
    return path


def _theme_only_deck(path):
    """No run names a font, so the theme is the only reading there is."""

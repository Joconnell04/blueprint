class DeckFonts(unittest.TestCase):
    """Q11: the fonts are the ones the runs use, not the ones the theme claims."""

    def test_the_theme_does_not_win_over_the_runs(self):
        fonts = deck("montserrat")["fonts"]
        self.assertNotIn("Calibri", fonts.values(),
                         "the theme says Calibri and every run says Montserrat")
        self.assertEqual(fonts["minor"], "Montserrat")
        self.assertEqual(ef.deck_tokens(deck("montserrat"))["fonts"]["body"], "Montserrat")

    def test_a_weight_suffix_stays_on_a_face_the_file_declares(self):
        self.assertEqual(deck("montserrat")["fonts"]["major"], "Montserrat SemiBold")
        self.assertIn("Montserrat SemiBold", ef.declared_typefaces(FIXTURES["montserrat_pptx"]))
        self.assertEqual(ef.deck_tokens(deck("montserrat"))["fonts"]["display"], "Montserrat SemiBold")

    def test_split_faces_collapse_to_the_family_name(self):
        # Body copy is half Montserrat Light, so neither face carries the family alone.
        self.assertEqual(deck("montserrat")["fonts"]["minor"], "Montserrat")
        why = RESULTS["montserrat"]["evidence"]["deck.fonts.minor"]
        self.assertIn("Montserrat Light", why)
        self.assertIn("characters", why)
        self.assertGreaterEqual(conf("montserrat", "deck.fonts.minor"), 0.8)

    def test_a_divider_slide_does_not_set_the_font(self):
        # The divider is set in Calibri: furniture slides are not where the body font lives.
        self.assertNotIn("Calibri", deck("montserrat")["fonts"].values())

    def test_the_theme_answers_when_no_run_names_a_font(self):
        fonts = deck("theme_only")["fonts"]
        self.assertEqual(fonts["minor"], "Calibri")
        self.assertEqual(fonts["major"], "Calibri")
        self.assertIn("no run names a font", RESULTS["theme_only"]["evidence"]["deck.fonts.minor"])

    def test_declared_typefaces_are_the_ones_the_file_names(self):
        declared = ef.declared_typefaces(FIXTURES["montserrat_pptx"])
        self.assertTrue({"Montserrat", "Montserrat Light", "Montserrat SemiBold", "Calibri"} <= declared)
        self.assertNotIn("Montserrat Bold", declared, "an unused weight is not a face of the file")
        plain = ef.declared_typefaces(FIXTURES["theme_only_pptx"])
        self.assertIn("Calibri", plain)
        self.assertFalse([f for f in plain if f.startswith("Montserrat")])


class DeckMeasure(unittest.TestCase):
    """Q18: `furniture.body`, the content measure the column module is cut from."""

    def measure(self, name="measure"):
        return RESULTS[name]["format"]["deck"]["furniture"]["body"]

    def test_the_measure_is_the_one_the_fixture_was_built_on(self):
        want, got = make_fixtures.MEASURE, self.measure()
        for key in ("x", "y", "w", "h"):
            self.assertAlmostEqual(got[key], want[key], delta=2, msg=key)

    def test_a_shape_in_the_margin_does_not_widen_the_measure(self):
        # The legend sits at x=30 and the band runs to x=930 on all three slides;
        # a measure taken from the extremes would read 30 wide by 900.
        got = self.measure()
        self.assertEqual(got["x"], 60)
        self.assertEqual(got["x"] + got["w"], 900)

    def test_the_band_runs_from_the_headline_to_the_source(self):
        furniture = RESULTS["measure"]["format"]["deck"]["furniture"]
        head, body, source = furniture["headline"], furniture["body"], furniture["source"]
        self.assertEqual(body["y"], head["y"] + head["h"])
        self.assertEqual(body["y"] + body["h"], source["y"])

    def test_the_measure_carries_its_grid_cell(self):
        self.assertEqual(self.measure()["cell"], ef.cell_of(60, 160))

    def test_the_evidence_counts_shapes_and_slides(self):
        why = RESULTS["measure"]["evidence"]["deck.furniture.body"]
